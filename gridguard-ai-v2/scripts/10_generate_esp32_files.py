BYTES_PER_LINE = 12


def write_model_header(tflite_path, out_path):
    data = tflite_path.read_bytes()
    lines = ["#pragma once", "#include <cstdint>", "", "// GridGuard AI v2 - INT8 TFLite model for ESP32-S3",
             "// Generated by scripts/10_generate_esp32_files.py", "", "alignas(16) const unsigned char gridguard_model_tflite[] = {"]
    body = []
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE]
        line = "  " + ", ".join(f"0x{b:02x}" for b in chunk) + ","
        body.append(line)
    lines.extend(body)
    lines.append("};")
    lines.append("")
    lines.append(f"const unsigned int gridguard_model_tflite_len = {len(data)};")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return len(data)


def fmt_float_list(values, per_line=8):
    parts = [f"{v:.6f}f" for v in values]
    lines = []
    for i in range(0, len(parts), per_line):
        lines.append("    " + ", ".join(parts[i:i + per_line]) + ",")
    return "\n".join(lines)


def write_config_header(out_path):
    norm = np.load(NORM_PARAMS_NPZ)
    mean, scale = norm["mean"], norm["scale"]
    with open(QUANT_PARAMS_JSON) as f:
        q = json.load(f)
    inp, outp = q["input"], q["output"]

    class_lines = ", ".join(f'"{CLASS_NAMES[i]}"' for i in range(len(CLASS_NAMES)))

    header = f"""#pragma once

// GridGuard AI v2 - ESP32-S3 configuration
// Scaling + quantization parameters extracted from the training pipeline.
// Normalization: x_norm[i] = (x_raw[i] - GG_MEAN[i]) / GG_SCALE[i]  (i = 0..39)
// Then quantize: q = round(x_norm / GG_INPUT_SCALE) + GG_INPUT_ZERO_POINT

#define GG_WINDOW_LEN                 {WINDOW_LEN}
#define GG_NUM_INPUTS                 {int(inp["shape"][1])}
#define GG_NUM_OUTPUTS                {int(outp["shape"][1])}
#define GG_INPUT_DTYPE                "int8"
#define GG_OUTPUT_DTYPE               "int8"

static const char* const GG_CLASS_NAMES[GG_NUM_OUTPUTS] = {{ {class_lines} }};

// Model I/O quantization (from gridguard_v2_int8.tflite)
const float GG_INPUT_SCALE   = {inp["scale"]:.9f}f;
const int   GG_INPUT_ZERO_POINT = {int(inp["zero_point"])};
const float GG_OUTPUT_SCALE  = {outp["scale"]:.9f}f;
const int   GG_OUTPUT_ZERO_POINT = {int(outp["zero_point"])};

// Per-feature z-score normalization (fitted on training data only)
const float GG_MEAN[GG_NUM_INPUTS] = {{
{fmt_float_list(mean)}
}};

const float GG_SCALE[GG_NUM_INPUTS] = {{
{fmt_float_list(scale)}
}};
"""
    out_path.write_text(header, encoding="utf-8")
    return mean, scale


