    no_fire_thr = float(cfg["no_fire_cutoff"])

    # ---------------------------------------------------------- model header
    data = INT8_TFLITE.read_bytes()
    lines = [
        "// GridGuard Fire AI - INT8 TensorFlow Lite model (TensorFlow Lite Micro).",
        "// Auto-generated by scripts/11_prepare_esp32_deployment.py - do not edit.",
        "// Input: int8 [1, %d, %d, 3], Output: int8 [1, 1] (FIRE probability)." % (size, size),
        f"// Model size: {len(data)} bytes.",
        "#pragma once",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "static const unsigned char gridguard_fire_model_int8[] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
        lines.append("  " + chunk + ("," if i + 16 < len(data) else ""))
    lines += [
        "};",
        "",
        "static const unsigned int gridguard_fire_model_int8_len = %d;" % len(data),
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
    ]
