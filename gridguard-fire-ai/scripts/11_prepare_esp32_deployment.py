from _helpers import decode_resize_rgb, load_manifest, preprocess_rgb  # noqa: E402


def main():
    cfg = json.loads(FINAL_CONFIG_JSON.read_text(encoding="utf-8"))
    q = json.loads(QUANT_PARAMS_JSON.read_text(encoding="utf-8"))
    size = int(cfg["input_size"])
    in_scale = float(q["input"]["scale"])
    in_zp = int(q["input"]["zero_point"])
    out_scale = float(q["output"]["scale"])
    out_zp = int(q["output"]["zero_point"])

    rows = _sample_test_images(60)

    keras_model = tf.keras.models.load_model(FINAL_MODEL_KERAS)
    interp_float = tf.lite.Interpreter(model_path=str(FLOAT_TFLITE))
    interp_float.allocate_tensors()
    fd = interp_float.get_input_details()[0]
    fo = interp_float.get_output_details()[0]

    interp_int8 = tf.lite.Interpreter(model_path=str(INT8_TFLITE))
    interp_int8.allocate_tensors()
    inn = interp_int8.get_input_details()[0]
    outn = interp_int8.get_output_details()[0]

    out_rows = []
    for r in rows:
        pixels = decode_resize_rgb(Path(r["path"]).read_bytes(), (size, size))
        x = preprocess_rgb(pixels)[None, ...]

        # 1) Keras training path
        p_keras = float(keras_model.predict(x, verbose=0)[0, 0])

        # 2) Float32 TFLite path
        interp_float.set_tensor(fd["index"], x)
        interp_float.invoke()
        p_float = float(interp_float.get_tensor(fo["index"])[0, 0])

        # 3) Simulated ESP32 INT8 path (exact firmware math)
        q_in = np.clip(np.round(x / in_scale + in_zp), -128, 127).astype(np.int8)
        interp_int8.set_tensor(inn["index"], q_in)
        interp_int8.invoke()
        q_out = interp_int8.get_tensor(outn["index"])[0, 0]
        p_int8 = float((q_out - out_zp) * out_scale)

        out_rows.append({
            "image": Path(r["path"]).name,
            "true_label": int(r["label"]),
            "keras_prob": f"{p_keras:.5f}",
            "float_tflite_prob": f"{p_float:.5f}",
            "int8_esp32_prob": f"{p_int8:.5f}",
            "diff_keras_float": f"{abs(p_keras - p_float):.5f}",
            "diff_keras_int8": f"{abs(p_keras - p_int8):.5f}",
        })

    with open(ROOT / "results" / "esp32_path_verification.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out_rows[0].keys()))
        w.writeheader()
        w.writerows(out_rows)

    d_float = np.abs(np.array([float(r["keras_prob"]) for r in out_rows]) -
                     np.array([float(r["float_tflite_prob"]) for r in out_rows]))
    d_int8 = np.abs(np.array([float(r["keras_prob"]) for r in out_rows]) -
                    np.array([float(r["int8_esp32_prob"]) for r in out_rows]))
    print("ESP32 preprocessing verification on", len(rows), "unseen test images")
    print(f"  Keras vs float TFLite : max={d_float.max():.5f}  mean={d_float.mean():.5f}")
    print(f"  Keras vs INT8(ESP32)  : max={d_int8.max():.5f}  mean={d_int8.mean():.5f}")
    return 0


